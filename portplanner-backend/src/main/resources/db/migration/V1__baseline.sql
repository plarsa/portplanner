-- Baslinje för PortPlanner: samlar alla tidigare databasförändringar (V1-V13) i ett schema.

-- Personer (medlemmar och kontakter i hamnregistret)
CREATE TABLE persons (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name           VARCHAR(100) NOT NULL,
    last_name            VARCHAR(100) NOT NULL,
    email                VARCHAR(255) NOT NULL UNIQUE,
    phone                VARCHAR(50),
    address              VARCHAR(255),
    postal_code          VARCHAR(20),
    property_designation VARCHAR(100),
    notes                CLOB
);

-- Inloggningskonton. username följer alltid e-postadressen. Konfigurerad superadmin lagras aldrig här.
CREATE TABLE app_users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username             VARCHAR(100) NOT NULL UNIQUE,
    email                VARCHAR(255),
    password_hash        VARCHAR(255) NOT NULL,
    status               VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    last_login_at        TIMESTAMP,
    created_at           TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    must_change_password BOOLEAN      NOT NULL DEFAULT FALSE,
    person_id            BIGINT REFERENCES persons (id)
);

-- E-post är unik när den är satt (flera NULL tillåts). En person har högst ett konto.
CREATE UNIQUE INDEX uq_app_users_email  ON app_users (email);
CREATE UNIQUE INDEX uq_app_users_person ON app_users (person_id);

-- Rolltilldelningar (roll:nivå) per konto
CREATE TABLE app_user_roles (
    user_id      BIGINT       NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    role_name    VARCHAR(100) NOT NULL,
    access_level VARCHAR(2)   NOT NULL,
    PRIMARY KEY (user_id, role_name)
);

-- Tillåtna inloggningsmetoder per konto
CREATE TABLE app_user_login_methods (
    user_id BIGINT      NOT NULL REFERENCES app_users (id) ON DELETE CASCADE,
    method  VARCHAR(50) NOT NULL,
    PRIMARY KEY (user_id, method)
);

CREATE TABLE boats (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model     VARCHAR(200) NOT NULL,
    length_m  NUMERIC(6,2) NOT NULL,
    width_m   NUMERIC(6,2) NOT NULL,
    draft_m   NUMERIC(6,2),
    owner_id  BIGINT NOT NULL REFERENCES persons (id),
    hull_type VARCHAR(20)
);

CREATE TABLE docks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(1000),
    layout_json CLOB
);

CREATE TABLE slips (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slip_number  VARCHAR(20) NOT NULL,
    max_length_m NUMERIC(6,2) NOT NULL,
    max_width_m  NUMERIC(6,2) NOT NULL,
    max_draft_m  NUMERIC(6,2),
    dock_id      BIGINT NOT NULL REFERENCES docks (id),
    status       VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
    mooring_type VARCHAR(100),
    side         VARCHAR(20),
    category     VARCHAR(50),
    notes        VARCHAR(2000),
    UNIQUE (dock_id, slip_number)
);

CREATE TABLE assignments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    boat_id       BIGINT NOT NULL REFERENCES boats (id),
    slip_id       BIGINT NOT NULL REFERENCES slips (id),
    assigned_date DATE NOT NULL,
    end_date      DATE,
    status        VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
);

CREATE TABLE queue_entries (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id       BIGINT NOT NULL REFERENCES persons (id),
    boat_id         BIGINT REFERENCES boats (id),
    requested_date  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notes           VARCHAR(2000),
    status          VARCHAR(20) NOT NULL DEFAULT 'WAITING',
    offered_slip_id BIGINT REFERENCES slips (id)
);

CREATE TABLE mail_threads (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gmail_thread_id    VARCHAR(255) NOT NULL UNIQUE,
    subject            VARCHAR(500),
    from_email         VARCHAR(255),
    received_at        TIMESTAMP NOT NULL,
    raw_content        CLOB,
    ai_suggested_reply CLOB,
    status             VARCHAR(20) NOT NULL DEFAULT 'NEW',
    linked_person_id   BIGINT REFERENCES persons (id)
);

CREATE TABLE audit_logs (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    event_type   VARCHAR(50)  NOT NULL,
    entity_type  VARCHAR(50),
    entity_id    BIGINT,
    description  VARCHAR(500) NOT NULL,
    performed_by VARCHAR(100)
);

CREATE INDEX idx_audit_occurred_at ON audit_logs (occurred_at DESC);
CREATE INDEX idx_audit_entity_type ON audit_logs (entity_type);

CREATE TABLE tariffs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(100)  NOT NULL,
    category      VARCHAR(50)   NOT NULL,
    annual_fee_kr DECIMAL(10,2) NOT NULL,
    valid_from    DATE          NOT NULL,
    valid_to      DATE,
    description   VARCHAR(500)
);

-- Uppläggningsplatser (modulen storage)
CREATE TABLE winter_seasons (
    id         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    "year"     INT          NOT NULL,
    name       VARCHAR(255) NOT NULL,
    start_date DATE,
    end_date   DATE,
    status     VARCHAR(20)  NOT NULL DEFAULT 'PLANNING'
);

CREATE TABLE haul_out_slots (
    id         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    season_id  BIGINT NOT NULL REFERENCES winter_seasons (id),
    slot_date  DATE   NOT NULL,
    start_time TIME   NOT NULL,
    end_time   TIME   NOT NULL,
    capacity   INT    NOT NULL DEFAULT 1
);

CREATE TABLE haul_out_bookings (
    id           BIGINT    GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    slot_id      BIGINT    NOT NULL REFERENCES haul_out_slots (id),
    boat_id      BIGINT    NOT NULL REFERENCES boats (id),
    person_id    BIGINT    NOT NULL REFERENCES persons (id),
    requested_at TIMESTAMP NOT NULL DEFAULT NOW(),
    status       VARCHAR(20) NOT NULL DEFAULT 'REQUESTED'
);

CREATE TABLE storage_yards (
    id                   BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    season_id            BIGINT       NOT NULL REFERENCES winter_seasons (id),
    name                 VARCHAR(255) NOT NULL,
    background_image_url VARCHAR(1024),
    origin_pixel_x       DOUBLE PRECISION,
    origin_pixel_y       DOUBLE PRECISION,
    pixels_per_meter     DOUBLE PRECISION,
    lane_margin_m        DECIMAL(5,2) DEFAULT 0.50
);

CREATE TABLE storage_yard_boundary_points (
    id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    yard_id     BIGINT NOT NULL REFERENCES storage_yards (id),
    point_order INT    NOT NULL,
    x_meters    DECIMAL(10,3) NOT NULL,
    y_meters    DECIMAL(10,3) NOT NULL
);

CREATE TABLE storage_packing_groups (
    id             BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    yard_id        BIGINT       NOT NULL REFERENCES storage_yards (id),
    name           VARCHAR(255) NOT NULL,
    retrieval_note VARCHAR(1000)
);

CREATE TABLE storage_placements (
    id               BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    yard_id          BIGINT NOT NULL REFERENCES storage_yards (id),
    booking_id       BIGINT NOT NULL REFERENCES haul_out_bookings (id),
    x_meters         DECIMAL(10,3) NOT NULL DEFAULT 0,
    y_meters         DECIMAL(10,3) NOT NULL DEFAULT 0,
    rotation_deg     DECIMAL(7,3)  NOT NULL DEFAULT 0,
    width_meters     DECIMAL(6,2)  NOT NULL,
    length_meters    DECIMAL(6,2)  NOT NULL,
    packing_group_id BIGINT REFERENCES storage_packing_groups (id),
    order_in_group   INT,
    status           VARCHAR(20) NOT NULL DEFAULT 'PLANNED'
);

CREATE TABLE pricing_rules (
    id                            BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    season_id                     BIGINT        NOT NULL REFERENCES winter_seasons (id),
    price_per_sqm                 DECIMAL(10,2) NOT NULL,
    extra_width_threshold_m       DECIMAL(6,2),
    extra_width_surcharge_per_dm  DECIMAL(10,2),
    extra_length_threshold_m      DECIMAL(6,2),
    extra_length_surcharge_per_dm DECIMAL(10,2),
    min_price                     DECIMAL(10,2)
);
